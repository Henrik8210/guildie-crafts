local function GuildWorkshopTest_BuildGearIndexes()
    GuildWorkshopTest_GearByName = {}
    for _, gear in ipairs(GuildWorkshopTest_Gear) do
        gear.label = gear.name .. " (" .. gear.sockets .. ")"
        GuildWorkshopTest_GearByName[gear.name] = gear
    end
end

if GuildWorkshopTest_PvpGear then
    for _, gear in ipairs(GuildWorkshopTest_PvpGear) do
        table.insert(GuildWorkshopTest_Gear, gear)
    end
end

GuildWorkshopTest_BuildGearIndexes()

function GuildWorkshopTest_GearMatchesClass(gear, className)
    if not gear or not className or className == "" then
        return false
    end
    if gear.classes then
        for _, token in ipairs(gear.classes) do
            if token == className then
                return true
            end
        end
        return false
    end
    return gear.class == className
end

function GuildWorkshopTest_GetGearByCategory(category)
    local results = {}
    for _, gear in ipairs(GuildWorkshopTest_Gear) do
        if gear.category == category then
            table.insert(results, gear)
        end
    end
    return results
end

function GuildWorkshopTest_GetGearByClass(className)
    local results = {}
    for _, gear in ipairs(GuildWorkshopTest_GetGearByCategory("PVP")) do
        if GuildWorkshopTest_GearMatchesClass(gear, className) then
            table.insert(results, gear)
        end
    end
    table.sort(results, function(a, b)
        return a.name < b.name
    end)
    return results
end

function GuildWorkshopTest_GetGearList()
    return GuildWorkshopTest_Gear
end

function GuildWorkshopTest_GetGearByName(name)
    return name and GuildWorkshopTest_GearByName[name]
end

function GuildWorkshopTest_GetGearItemId(name)
    local gear = GuildWorkshopTest_GetGearByName(name)
    return gear and gear.itemId
end

function GuildWorkshopTest_GetGearByRaid(raid)
    local results = {}
    for _, gear in ipairs(GuildWorkshopTest_Gear) do
        if gear.category == "PVE" and gear.raid == raid then
            table.insert(results, gear)
        end
    end
    table.sort(results, function(a, b)
        return a.name < b.name
    end)
    return results
end
